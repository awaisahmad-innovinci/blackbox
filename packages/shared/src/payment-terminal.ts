/** Desktop integrated payment terminal (main process + IPC). */

export type PaymentTerminalTransport = "tcp" | "serial" | "bluetooth";

export type PaymentTerminalFramerId =
  | "delimiter"
  | "length-prefix"
  | "newline";

export type PaymentStatus =
  | "APPROVED"
  | "DECLINED"
  | "CANCELLED"
  | "PENDING"
  | "UNKNOWN"
  | "TIMEOUT";

export type PaymentTerminalProviderId =
  | "OPAY_ECR"
  | "NEXO"
  | "MEEZAN_ECR"
  | "MCB_ECR"
  | "ALFALAH_ECR"
  | "ALLIED_ECR";

export interface PaymentRequest {
  invoiceId: string;
  amount: number;
  currency: "PKR";
  /** Idempotent terminal reference (orderNo). Generated by bridge when omitted. */
  transactionId?: string;
}

export interface PaymentResult {
  status: PaymentStatus;
  amount: number;
  transactionId?: string;
  terminalTransactionId?: string;
  authorizationCode?: string;
  referenceNumber?: string;
  message?: string;
  raw?: unknown;
}

/** Persisted payment attempt lifecycle (desktop SQLite). */
export type PaymentTerminalAttemptStatus =
  | "CREATED"
  | "SENT"
  | "APPROVED"
  | "DECLINED"
  | "CANCELLED"
  | "PENDING"
  | "UNKNOWN"
  | "TIMEOUT";

/** Non-secret settings exposed to renderer for configuration UI. */
export interface PaymentTerminalSettings {
  /** When true, SalePage can require terminal APPROVED before posting card/split card. */
  integratedCheckout: boolean;
  providerId: PaymentTerminalProviderId;
  transport: PaymentTerminalTransport;
  framerId: PaymentTerminalFramerId;
  host: string;
  port: number;
  serialPort: string;
  baudRate: number;
  terminalId: string;
  merchantId: string;
  operationTimeoutMs: number;
  connectTimeoutMs: number;
}

